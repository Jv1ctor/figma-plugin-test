import { TOKENS, type Theme } from "./theme.ts";

/** globals.css in the shadcn/ui (Tailwind v4) format. */
export function themeToCss(theme: Theme): string {
  const block = (selector: string, values: Theme["light"], withRadius: boolean) => {
    const lines = TOKENS.map((t) => `  --${t}: ${values[t]};`);
    if (withRadius) lines.unshift(`  --radius: ${theme.radius}rem;`);
    return `${selector} {\n${lines.join("\n")}\n}`;
  };

  const inline = [
    "  --radius-sm: calc(var(--radius) - 4px);",
    "  --radius-md: calc(var(--radius) - 2px);",
    "  --radius-lg: var(--radius);",
    "  --radius-xl: calc(var(--radius) + 4px);",
    ...TOKENS.map((t) => `  --color-${t}: var(--${t});`),
  ].join("\n");

  return `/* ${theme.name} — generated by Token Bridge */
@import "tailwindcss";

@custom-variant dark (&:is(.dark *));

${block(":root", theme.light, true)}

${block(".dark", theme.dark, false)}

@theme inline {
${inline}
}

@layer base {
  * {
    @apply border-border outline-ring/50;
  }
  body {
    @apply bg-background text-foreground;
  }
}
`;
}
